// Generates src/styles.css (tokens expanded with fallbacks, shared with @byos/react) and
// src/styles.ts (the same CSS as a string, for renderers that inject it).
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

execFileSync('python3', ['../react/src/build-css.py', 'src/styles.src.css', 'src/styles.css']);
const css = readFileSync('src/styles.css', 'utf8');
writeFileSync('src/styles.ts', `// Generated by build-styles.mjs from styles.src.css. Do not edit.\nexport const PALETTE_CSS = ${JSON.stringify(css)};\n`);
